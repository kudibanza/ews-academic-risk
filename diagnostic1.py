import pandas as pd
reg = pd.read_csv('data/raw/studentRegistration.csv')
print('date_registration dtype:', reg['date_registration'].dtype)
print('date_registration describe:')
print(reg['date_registration'].describe())
print()
print('date_registration non-integer values:')
non_int = reg['date_registration'].dropna()
non_int = non_int[non_int != non_int.astype(int)]
print(non_int.head(20))
print(f'count: {len(non_int)}')
print()
print('date_unregistration dtype:', reg['date_unregistration'].dtype)
print('date_unregistration describe:')
print(reg['date_unregistration'].describe())
print()
print('date_unregistration non-integer values:')
non_int2 = reg['date_unregistration'].dropna()
non_int2 = non_int2[non_int2 != non_int2.astype(int)]
print(non_int2.head(20))
print(f'count: {len(non_int2)}')
print()
print('Rows with date_registration null:')
print(reg[reg['date_registration'].isna()].head(10))
print(f'count: {reg["date_registration"].isna().sum()}') 