"""
OULAD schema and relational integrity audit.
Reports only — never modifies, drops, or imputes data.
Run from project root: python -m src.data.audit_schema
"""
import json
from pathlib import Path

import pandas as pd

RAW_DIR = Path("data/raw")
REPORT_DIR = Path("experiments/01_data_audit")
REPORT_MD = REPORT_DIR / "audit_report.md"
REPORT_JSON = REPORT_DIR / "audit_summary.json"

# ---- Expected schema (from UCI OULAD documentation) ----
EXPECTED_COLUMNS = {
    "courses.csv": ["code_module", "code_presentation", "module_presentation_length"],
    "assessments.csv": ["code_module", "code_presentation", "id_assessment",
                        "assessment_type", "date", "weight"],
    "vle.csv": ["id_site", "code_module", "code_presentation",
                "activity_type", "week_from", "week_to"],
    "studentAssessment.csv": ["id_assessment", "id_student", "date_submitted",
                              "is_banked", "score"],
    "studentVle.csv": ["code_module", "code_presentation", "id_student",
                       "id_site", "date", "sum_click"],
    "studentInfo.csv": ["code_module", "code_presentation", "id_student",
                        "gender", "region", "highest_education",
                        "imd_band", "age_band", "num_of_prev_attempts",
                        "studied_credits", "disability", "final_result"],
    "studentRegistration.csv": ["code_module", "code_presentation", "id_student",
                                "date_registration", "date_unregistration"],
}

# ---- Canonical reference counts (UCI OULAD documentation) ----
CANONICAL = {
    "unique_students": 32593,
    "studentVle_rows": 10655280,
    "studentAssessment_rows": 173912,
    "modules": 7,
    "presentations": 4,
    "module_presentations": 22,
}

CUTOFFS = {"W2": 14, "W4": 28, "W6": 42, "W8": 56}

# ---- Helper ----
def load(name: str) -> pd.DataFrame:
    path = RAW_DIR / name
    if not path.exists():
        raise FileNotFoundError(f"Missing required file: {path}")
    return pd.read_csv(path)


def section(title: str) -> str:
    return f"\n## {title}\n"


def main() -> None:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    summary = {}
    md = ["# OULAD Data Audit Report", "",
          "Generated by `src/data/audit_schema.py`. Reports only; no data modified."]

    # ---- 1. Schema and row counts ----
    md.append(section("1. Schema and row counts"))
    md.append("| file | rows | cols | missing cols | extra cols | null counts |")
    md.append("|---|---|---|---|---|---|")
    tables = {}
    for name, expected in EXPECTED_COLUMNS.items():
        df = load(name)
        tables[name] = df
        missing = [c for c in expected if c not in df.columns]
        extra = [c for c in df.columns if c not in expected]
        nulls = {c: int(df[c].isna().sum()) for c in df.columns if df[c].isna().any()}
        nulls_str = ", ".join(f"{k}={v}" for k, v in nulls.items()) or "none"
        md.append(f"| {name} | {len(df):,} | {len(df.columns)} | "
                  f"{', '.join(missing) or '—'} | {', '.join(extra) or '—'} | {nulls_str} |")
        summary[name] = {
            "rows": len(df),
            "cols": len(df.columns),
            "missing_columns": missing,
            "extra_columns": extra,
            "null_counts": nulls,
        }

    # ---- 2. Key uniqueness ----
    md.append(section("2. Key uniqueness"))
    checks = [
        ("studentInfo", tables["studentInfo.csv"],
         ["id_student", "code_module", "code_presentation"]),
        ("courses", tables["courses.csv"],
         ["code_module", "code_presentation"]),
        ("assessments", tables["assessments.csv"], ["id_assessment"]),
        ("vle", tables["vle.csv"], ["id_site"]),
        ("studentRegistration", tables["studentRegistration.csv"],
         ["id_student", "code_module", "code_presentation"]),
    ]
    md.append("| table | key | rows | unique keys | duplicates |")
    md.append("|---|---|---|---|---|")
    for label, df, key in checks:
        n_rows = len(df)
        n_unique = len(df.drop_duplicates(subset=key))
        dup = n_rows - n_unique
        md.append(f"| {label} | {', '.join(key)} | {n_rows:,} | {n_unique:,} | {dup:,} |")
        summary[f"key_{label}"] = {"rows": n_rows, "unique": n_unique, "duplicates": dup}

    # ---- 3. Referential integrity ----
    md.append(section("3. Referential integrity"))
    info = tables["studentInfo.csv"]
    reg = tables["studentRegistration.csv"]
    vle = tables["vle.csv"]
    svle = tables["studentVle.csv"]
    sa = tables["studentAssessment.csv"]
    asm = tables["assessments.csv"]

    info_key = set(zip(info["id_student"], info["code_module"], info["code_presentation"]))
    reg_key = set(zip(reg["id_student"], reg["code_module"], reg["code_presentation"]))
    svle_key = set(zip(svle["id_student"], svle["code_module"], svle["code_presentation"]))
    sa_ids = set(sa["id_student"])
    info_ids = set(info["id_student"])

    ri_checks = [
        ("studentRegistration -> studentInfo (composite key)",
         len(reg_key - info_key)),
        ("studentVle -> studentInfo (composite key)",
         len(svle_key - info_key)),
        ("studentAssessment.id_student -> studentInfo.id_student",
         len(sa_ids - info_ids)),
        ("studentVle.id_site -> vle.id_site",
         len(set(svle["id_site"]) - set(vle["id_site"]))),
        ("studentAssessment.id_assessment -> assessments.id_assessment",
         len(set(sa["id_assessment"]) - set(asm["id_assessment"]))),
    ]
    md.append("| check | orphan records |")
    md.append("|---|---|")
    for label, orphans in ri_checks:
        md.append(f"| {label} | {orphans:,} |")
        summary[f"ri_{label}"] = orphans

    # ---- 4. Canonical counts ----
    md.append(section("4. Canonical counts"))
    observed = {
        "unique_students": int(info["id_student"].nunique()),
        "studentVle_rows": len(svle),
        "studentAssessment_rows": len(sa),
        "modules": int(info["code_module"].nunique()),
        "presentations": int(info["code_presentation"].nunique()),
        "module_presentations": int(
            info[["code_module", "code_presentation"]].drop_duplicates().shape[0]),
    }
    md.append("| metric | observed | canonical | match |")
    md.append("|---|---|---|---|")
    for k, canon in CANONICAL.items():
        obs = observed[k]
        match = "yes" if obs == canon else "NO"
        md.append(f"| {k} | {obs:,} | {canon:,} | {match} |")
        summary[f"canonical_{k}"] = {"observed": obs, "canonical": canon, "match": obs == canon}

    # ---- 5. Target distribution ----
    md.append(section("5. Target distribution (final_result)"))
    md.append("### By presentation")
    md.append("| presentation | N | Pass | Fail | Withdrawn | Distinction | risk (Withdrawn∪Fail) |")
    md.append("|---|---|---|---|---|---|---|")
    for pres, g in info.groupby("code_presentation"):
        n = len(g)
        counts = g["final_result"].value_counts()
        risk = (counts.get("Withdrawn", 0) + counts.get("Fail", 0)) / n
        md.append(
            f"| {pres} | {n:,} | {counts.get('Pass', 0):,} | "
            f"{counts.get('Fail', 0):,} | {counts.get('Withdrawn', 0):,} | "
            f"{counts.get('Distinction', 0):,} | {risk:.3f} |"
        )
        summary[f"target_{pres}"] = {
            "n": n,
            "Pass": int(counts.get("Pass", 0)),
            "Fail": int(counts.get("Fail", 0)),
            "Withdrawn": int(counts.get("Withdrawn", 0)),
            "Distinction": int(counts.get("Distinction", 0)),
            "risk_proportion": round(float(risk), 4),
        }

    md.append("### By module")
    md.append("| module | N | risk proportion |")
    md.append("|---|---|---|")
    for mod, g in info.groupby("code_module"):
        n = len(g)
        risk = (g["final_result"].isin(["Withdrawn", "Fail"])).sum() / n
        md.append(f"| {mod} | {n:,} | {risk:.3f} |")

    # ---- 6. Temporal consistency ----
    md.append(section("6. Temporal consistency"))
    courses = tables["courses.csv"]
    max_len = int(courses["module_presentation_length"].max())
    md.append(f"- Max `module_presentation_length` across all runs: **{max_len} days**")
    for w, d in CUTOFFS.items():
        status = "OK" if d <= max_len else "BEYOND COURSE LENGTH"
        md.append(f"- {w} cutoff = {d} days → {status}")

    # Check activity exists before W2
    svle_w2 = svle[svle["date"] <= CUTOFFS["W2"]]
    n_students_w2 = svle_w2["id_student"].nunique()
    md.append(f"- Distinct students with VLE activity by W2: **{n_students_w2:,}** "
              f"(of {observed['unique_students']:,} unique students)")

    # date_unregistration type
    unreg = reg["date_unregistration"]
    md.append(f"- `date_unregistration`: dtype={unreg.dtype}, "
              f"non-null={int(unreg.notna().sum()):,}, null={int(unreg.isna().sum()):,}")
    summary["temporal"] = {
        "max_module_length": max_len,
        "students_with_activity_by_W2": int(n_students_w2),
        "date_unregistration_dtype": str(unreg.dtype),
        "date_unregistration_nonnull": int(unreg.notna().sum()),
        "date_unregistration_null": int(unreg.isna().sum()),
    }

    # ---- Write outputs ----
    REPORT_MD.write_text("\n".join(md), encoding="utf-8")
    REPORT_JSON.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(f"Report written to {REPORT_MD}")
    print(f"Summary written to {REPORT_JSON}")


if __name__ == "__main__":
    main()